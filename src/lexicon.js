// Свёртка казахских букв к близким русским — чтобы сравнивать написания:
// «Жетісу» ≡ «Жетысу», «Қонаев» ≡ «Конаев», «Ұлытау» ≡ «Улытау».
const KZ_FOLD = {
  ә: 'а', ғ: 'г', қ: 'к', ң: 'н', ө: 'о',
  ұ: 'у', ү: 'у', һ: 'х', і: 'и',
};

export function foldKz(s) {
  if (!s) return '';
  return String(s)
    .toLowerCase()
    .replace(/[әғқңөұүһі]/g, (ch) => KZ_FOLD[ch] ?? ch);
}

// Ключ для поиска в справочниках: свёртка казахских букв, ё→е, без пунктуации.
export function normalizeKey(name) {
  return foldKz(name)
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function canonicalProvinceStem(name) {
  if (!name) return null;
  const n = foldKz(name).replace(/[-\s]/g, '');
  for (const [key, canon] of PROVINCE_CANON) {
    if (n.includes(key)) return canon;
  }
  return null;
}

// Усечение падежных окончаний для нечёткого поиска в справочнике. Нужно как
// fallback: в адресе пишут «Абая», а в OSM — «Абай даңғылы»; ключи «абая» и
// «абай» не равны, но усечённые («аба») совпадают.
// Порядок: сначала длинные хвосты, чтобы не отрезать лишнего.
export const STEM_TAILS = [
  'ского', 'ской', 'ская', 'ские', 'ский', 'ого', 'его', 'ому', 'ему',
  'ыми', 'ими', 'ами', 'ями', 'ах', 'ях', 'ов', 'ев', 'ый', 'ий', 'ая', 'яя',
  'ое', 'ее', 'ой', 'ей', 'ем', 'ом', 'ым', 'им', 'ую', 'юю',
  'а', 'я', 'ы', 'и', 'е', 'у', 'ю', 'о', 'ь', 'й',
];

export function stemWord(word) {
  if (word.length <= 4 || /^\d+$/.test(word)) return word;
  for (const t of STEM_TAILS) {
    if (word.endsWith(t) && word.length - t.length >= 3) return word.slice(0, -t.length);
  }
  return word;
}

export function stemKey(name) {
  return normalizeKey(name)
    .split(' ')
    .filter(Boolean)
    .map(stemWord)
    .join(' ');
}
