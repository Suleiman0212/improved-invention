// Токен служебный? Проверяется по словарю и по производным «қаласы/облысы».
// «Республики» НЕ служебное — это часто название улицы («пр. Республики»
// в Шымкенте, Таразе и других городах).
export function isStopToken(token) {
  if (!token) return true;
  const t = token.toLowerCase().replace(/[.,;:()«»"'’]/g, '');
  if (!t) return true;
  if (STOP_TOKENS.has(t)) return true;
  if (t.startsWith('қалас') || t.startsWith('облыс')) return true;
  return false;
}

