// lowercase alias -> { name, province }
export const CITY_MAP = new Map();
for (const [name, province, aliases] of CITY_ROWS) {
  const info = { name, province };
  CITY_MAP.set(name.toLowerCase(), info);
  for (const a of aliases) CITY_MAP.set(a.toLowerCase(), info);
}

// Алиасы городов, отсортированные по длине: длинные первыми, чтобы «Нур-Султан»
// не распознавался как «Султан» и т. п.
export const CITY_ALIASES = [...CITY_MAP.keys()].sort((a, b) => b.length - a.length);

export function canonicalCity(name) {
  if (!name) return null;
  const info = CITY_MAP.get(name.trim().toLowerCase());
  return info ? info.name : null;
}

